"""Tables of I01 Steps 0-1 from rows_*.jsonl (written by repairs.py). Writes tables.txt beside this file."""
from __future__ import annotations

import collections
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent
ORDER = [("old", "qwen38_low"), ("old", "glm53"), ("old", "dsv41"),
         ("new", "qwen38_low"), ("new", "glm53"), ("new", "dsv41"), ("new", "haiku55"), ("new", "sonnet55_low"),
         ("new", "gemini38_low")]
NAME = {"qwen38_low": "Qwen", "glm53": "GLM", "dsv41": "DeepSeek", "haiku55": "Haiku", "sonnet55_low": "Sonnet",
        "gemini38_low": "Gemini"}
STAGE = {("old", "qwen38_low"): "s19", ("old", "glm53"): "s19", ("old", "dsv41"): "s20"}
SITS = [("no_one", "nobody near"), ("waiting_line", "lines"), ("conversation_group", "groups")]
MAIN = ["R0", "R1", "R2", "R3", "R4", "P", "R5", "R6"]
EXTRA = ["R4s", "Ps", "P1m", "R3_1m", "P5", "ALL", "R6x"]
# README Table 1e / 1a solver-alone (SA) rows: nobody near, lines, groups
README_SA = {("old", "qwen38_low"): (100, 0, 47), ("old", "glm53"): (93, 0, 52), ("old", "dsv41"): (83, 0, 45),
             ("new", "qwen38_low"): (97, 0, 46), ("new", "glm53"): (83, 0, 49), ("new", "dsv41"): (85, 0, 44),
             ("new", "haiku55"): (108, 0, 53), ("new", "sonnet55_low"): (108, 0, 47),
             ("new", "gemini38_low"): (104, 0, 54)}
GUESS_PERC = {"glm53": "+10 to +11.5", "dsv41": "+6", "qwen38_low": "+1"}
GUESS_ORACLE = {"qwen38_low": "+2.8", "glm53": "+9.5", "dsv41": "+8.7"}   # order inferred: wrong-target shares, old wording


def load():
    rows = {}
    for wording, model in ORDER:
        path = OUT / f"rows_{wording}_{model}.jsonl"
        if path.exists():
            rows[(wording, model)] = [json.loads(line) for line in path.open()]
    return rows


def cell(rs, k):
    s = sum(r[k] for r in rs)
    f = sum(r[k] and not r["C_rec"] for r in rs)
    b = sum(r["C_rec"] and not r[k] for r in rs)
    return s, f, b


def fmt(s, f, b):
    return f"{s} (+{f}/-{b})"


def main():
    rows = load()
    out = []
    p = out.append
    p("I01 Steps 0-1: counterfactual error budget. Generated by tables.py from rows_*.jsonl (repairs.py).")
    p("Cell format: successes (+flips fail->success / -breaks success->fail), against the recorded C verdict.")
    p("All 252 records per model: records that are not solver steps keep their recorded verdict in every arm.")
    p("")

    # ---------------------------------------------------------------- Step 0
    p("TABLE 0. Step 0: reproduction of recorded solver places (H.resolve with the recorded inputs) and R0 check")
    p(f"{'wording':8s}{'model':10s}{'records':>8s}{'solver':>8s}{'reprod':>8s}{'moved':>7s}{'C rec':>7s}"
      f"{'C replay':>9s}   R0 (nobody/lines/groups) vs README SA")
    for key, rs in rows.items():
        st = [r for r in rs if r["solver_step"]]
        rep = sum(r["reproduced"] for r in st)
        r0 = tuple(sum(r["R0"] for r in rs if r["situation"] == s) for s, _ in SITS)
        ok_replay = sum((r["C_replay_ok"] if r["solver_step"] else r["C_rec"]) for r in rs)
        p(f"{key[0]:8s}{NAME[key[1]]:10s}{len(rs):8d}{len(st):8d}{rep:8d}{len(st) - rep:7d}"
          f"{sum(r['C_rec'] for r in rs):7d}{ok_replay:9d}   {r0} vs {README_SA[key]}"
          f" {'agree' if r0 == README_SA[key] else 'DIFFER'}")
    p("")

    # ---------------------------------------------------------------- main table
    for label, keys in (("TABLE 1. Main repairs", MAIN), ("TABLE 1x. Extra and sensitivity arms", EXTRA)):
        p(f"{label}, per model x situation (n records; solver steps in brackets)")
        p(f"{'wording':8s}{'model':9s}{'situation':13s}{'n(st)':>9s}{'C':>5s}  " + "".join(f"{k:>14s}" for k in keys))
        for key, rs in rows.items():
            for s, sname in SITS + [(None, "all")]:
                sub = [r for r in rs if s is None or r["situation"] == s]
                st = sum(r["solver_step"] for r in sub)
                c = sum(r["C_rec"] for r in sub)
                p(f"{key[0]:8s}{NAME[key[1]]:9s}{sname:13s}{len(sub):5d}({st:3d}){c:5d}  "
                  + "".join(f"{fmt(*cell(sub, k)):>14s}" for k in keys))
            p("")
        p("")

    # ---------------------------------------------------------------- pre-registered: line failures
    p("TABLE 2. Pre-registered set: C line failures (waiting_line solver step, right target, not a success, place")
    p("outside the region or unreachable; RERUN R01). Flips among them per repair; breaks over ALL solver steps of the")
    p("model (all situations) and over line solver steps.")
    keys2 = MAIN + ["P1m", "R3_1m", "Ps", "P5", "ALL"]
    p(f"{'wording':8s}{'model':9s}{'n LF':>5s}  " + "".join(f"{k:>7s}" for k in keys2))
    for key, rs in rows.items():
        lf = [r for r in rs if r["line_failure"]]
        p(f"{key[0]:8s}{NAME[key[1]]:9s}{len(lf):5d}  flips " + "".join(f"{sum(r[k] for r in lf):7d}" for k in keys2))
        st = [r for r in rs if r["solver_step"]]
        p(f"{'':8s}{'':9s}{'':5s}  brk-all" + "".join(f"{sum(r['C_rec'] and not r[k] for r in st):6d} " for k in keys2))
        stl = [r for r in st if r["situation"] == "waiting_line"]
        p(f"{'':8s}{'':9s}{'':5s}  brk-ln " + "".join(f"{sum(r['C_rec'] and not r[k] for r in stl):6d} " for k in keys2))
    p("")

    # ---------------------------------------------------------------- criteria
    p("TABLE 3. Pre-registered criteria (old wording: s19 GLM, s20 DeepSeek)")
    og, od = rows.get(("old", "glm53")), rows.get(("old", "dsv41"))
    if og and od:
        def lf(rs, k):
            return sum(r[k] for r in rs if r["line_failure"]), sum(r["line_failure"] for r in rs)

        def brk(rs, k):
            return sum(r["C_rec"] and not r[k] for r in rs if r["solver_step"])
        pg, pd, r3g = lf(og, "P"), lf(od, "P"), lf(og, "R3")
        p(f"  P flips GLM {pg[0]} of {pg[1]} (success needs >= 15; kill half <= 8)")
        p(f"  P flips DeepSeek {pd[0]} of {pd[1]} (success needs >= 8; kill half <= 4)")
        p(f"  R3 flips GLM {r3g[0]} of {r3g[1]} (success needs >= 10; kill if <= 5 while breaking >= 3)")
        p(f"  breaks over all solver steps: P GLM {brk(og, 'P')}, P DeepSeek {brk(od, 'P')}, "
          f"R3 GLM {brk(og, 'R3')}, R3 DeepSeek {brk(od, 'R3')} (success needs <= 2 per model)")
        r3d = lf(od, "R3")
        p(f"  (R3 flips DeepSeek {r3d[0]} of {r3d[1]}; Qwen old: P {lf(rows[('old', 'qwen38_low')], 'P')}, "
          f"R3 {lf(rows[('old', 'qwen38_low')], 'R3')})")
        succ = pg[0] >= 15 and pd[0] >= 8 and r3g[0] >= 10 and max(brk(og, "P"), brk(od, "P")) <= 2
        kill = (pg[0] <= 8 and pd[0] <= 4) or (r3g[0] <= 5 and brk(og, "R3") >= 3)
        p(f"  Step-1 success part met: {succ}; kill part met: {kill}")
    p("")

    # ---------------------------------------------------------------- ceilings
    p("TABLE 4. Ceilings in percentage points of 252 (gain over recorded C, all records)")
    p(f"{'wording':8s}{'model':9s}{'C':>5s}" + "".join(f"{k:>8s}" for k in ["R1", "R2", "R3", "R4", "P"])
      + f"{'best':>10s}{'guess':>14s}{'R6':>8s}{'R6x':>8s}{'guess':>8s}{'R5':>8s}{'ALL':>8s}")
    for key, rs in rows.items():
        c = sum(r["C_rec"] for r in rs)
        d = {k: sum(r[k] for r in rs) - c for k in ["R1", "R2", "R3", "R4", "P", "R6", "R6x", "R5", "ALL"]}
        best = max(["R1", "R2", "R3", "R4", "P"], key=lambda k: d[k])
        pp = lambda x: f"{100 * x / len(rs):+.1f}"  # noqa: E731
        p(f"{key[0]:8s}{NAME[key[1]]:9s}{c:5d}" + "".join(f"{pp(d[k]):>8s}" for k in ["R1", "R2", "R3", "R4", "P"])
          + f"{pp(d[best]) + ' ' + best:>10s}{(GUESS_PERC.get(key[1], '-') if key[0] == 'old' else '-'):>14s}"
          + f"{pp(d['R6']):>8s}{pp(d['R6x']):>8s}{(GUESS_ORACLE.get(key[1], '-') if key[0] == 'old' else '-'):>8s}"
          + f"{pp(d['R5']):>8s}{pp(d['ALL']):>8s}")
    p("  R6 = oracle target on solver steps only; R6x adds the standard goal from the oracle target on non-solver")
    p("  records with status ok. Net gains (flips minus breaks); see TABLE 1 for flips and breaks separately.")
    p("")

    # ---------------------------------------------------------------- why line failures stay
    p("TABLE 5. Line failures that P does not flip: what the recorded constraints give the solver under P")
    for key, rs in rows.items():
        lf = [r for r in rs if r["line_failure"]]
        stay = [r for r in lf if not r["P"]]
        why = collections.Counter()
        for r in stay:
            ca_status = [s for k, s in zip(r["kinds"], r["uses_P"]) if k == "come_after"]
            if not r["has_come_after"]:
                why["no come_after stated"] += 1
            elif "used" not in ca_status:
                why["come_after stated but unusable under P (its people all dropped)"] += 1
            else:
                why["come_after used under P, still fails"] += 1
        also = collections.Counter()
        for r in stay:
            also["P1m flips"] += r["P1m"]
            also["R5 flips"] += r["R5"]
            also["P5 flips"] += r["P5"]
        p(f"  {key[0]} {NAME[key[1]]}: {len(stay)} of {len(lf)} stay; " + "; ".join(f"{k} {v}" for k, v in why.items())
          + " | of those: " + ", ".join(f"{k} {v}" for k, v in also.items()))
    p("")

    # ---------------------------------------------------------------- diagnostics
    p("TABLE 6. Diagnostics over solver steps (people scenes and nobody-near goal steps)")
    p(f"{'wording':8s}{'model':9s}{'steps':>6s}{'det':>6s}{'vis':>6s}{'match':>6s}{'miss':>6s}{'spur':>6s}"
      f"{'add~kept':>9s}{'unproj':>7s}{'strip':>6s}{'R4!=R4s':>8s}{'P!=Ps':>6s}{'needNA':>7s}{'liftNA':>7s}"
      f"{'m1m':>6s}")
    for key, rs in rows.items():
        st = [r for r in rs if r["solver_step"]]
        sm = lambda k: sum(r[k] for r in st)  # noqa: E731
        p(f"{key[0]:8s}{NAME[key[1]]:9s}{len(st):6d}{sm('n_det'):6d}{sm('n_vis'):6d}{sm('n_matched'):6d}"
          f"{sm('n_missed'):6d}{sm('n_spurious'):6d}{sm('n_added_near_kept'):9d}{sm('n_missed_unprojectable'):7d}"
          f"{sum(r['n_cons_stripped'] > 0 for r in st):6d}{sum(r['R4'] != r['R4s'] for r in st):8d}"
          f"{sum(r['P'] != r['Ps'] for r in st):6d}{sum(r['r5_needed_missing'] for r in st):7d}"
          f"{sm('r6_lift_failed'):7d}{sm('n_matched_1m'):6d}")
    p("  det/vis/match/miss/spur: people summed over steps (detected, visible true, matched at 0.5 m, missed true,")
    p("  unmatched detections). add~kept: added true people within 0.25 m of a detection (the pipeline's merge would")
    p("  drop one). unproj: missed people whose mark does not project (not added). strip: steps where R4 removed a")
    p("  number from some constraint. R4!=R4s, P!=Ps: steps whose verdict depends on the constraint rule for dropped")
    p("  numbers. needNA: group steps where the target person was not matched (R5 omits visible_to and face).")
    p("  liftNA: oracle target lift failed (recorded target kept). m1m: matched at 1.0 m.")
    p("")

    p("TABLE 6b. Oracle target: flips split by whether the recorded target was right")
    p(f"{'wording':8s}{'model':9s}{'wrongT':>7s}{'R6 flip':>8s}{'R6x flip':>9s}{'rightT fail':>12s}{'R6 flip':>8s}"
      f"{'R6x flip':>9s}{'R6 brk':>7s}{'R6x brk':>8s}{'R6 not tc':>10s}")
    for key, rs in rows.items():
        wrong = [r for r in rs if not r["target_correct"]]
        rf = [r for r in rs if r["target_correct"] and not r["C_rec"]]
        p(f"{key[0]:8s}{NAME[key[1]]:9s}{len(wrong):7d}{sum(r['R6'] for r in wrong):8d}{sum(r['R6x'] for r in wrong):9d}"
          f"{len(rf):12d}{sum(r['R6'] for r in rf):8d}{sum(r['R6x'] for r in rf):9d}"
          f"{sum(r['C_rec'] and not r['R6'] for r in rs):7d}{sum(r['C_rec'] and not r['R6x'] for r in rs):8d}"
          f"{sum(r['solver_step'] and not r['R6_tc'] for r in rs):10d}")
    p("  wrongT: records whose recorded target is wrong (any situation; includes not-ok records). rightT fail: right")
    p("  target but failed. R6 not tc: solver steps where the oracle target still scores as not the right target.")
    p("")

    p("TABLE 7. Extra: facing error of matched detections (|detected yaw - true yaw|, deg), 45-deg bins")
    p(f"{'wording':8s}{'model':9s}{'n':>6s}{'0-45':>7s}{'45-90':>7s}{'90-135':>7s}{'135-180':>8s}{'yaw None':>9s}"
      f"{'median':>8s}")
    for key, rs in rows.items():
        errs = sorted(e for r in rs if r["solver_step"] for e in r["facing_err_deg"])
        none = sum(r["facing_none"] for r in rs if r["solver_step"])
        bins = [sum(lo <= e < hi for e in errs) for lo, hi in ((0, 45), (45, 90), (90, 135), (135, 181))]
        med = errs[len(errs) // 2] if errs else float("nan")
        p(f"{key[0]:8s}{NAME[key[1]]:9s}{len(errs):6d}" + "".join(f"{b:7d}" for b in bins[:3]) + f"{bins[3]:8d}"
          f"{none:9d}{med:8.1f}")
    p("  Pooled over every solver step (one detection counted once per record; repeated draws of one scene are")
    p("  counted again). Caution: s21 Qwen and s23 GLM/DeepSeek people answers are cache copies of s19/s20.")
    (OUT / "tables.txt").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
